-- BESTIE production Name-City-Animal game
-- Two-player synchronous game. Server validates every answer against a
-- language-specific dictionary; blanks/invalid words score zero.
BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS unaccent;

CREATE TABLE IF NOT EXISTS public.name_city_animal_games (
  session_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  created_by uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  partner_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  language_code text NOT NULL CHECK (language_code IN ('tr','en','de','es','fr')),
  current_letter text NOT NULL DEFAULT 'A',
  round_number integer NOT NULL DEFAULT 1 CHECK (round_number BETWEEN 1 AND 5),
  total_rounds integer NOT NULL DEFAULT 5 CHECK (total_rounds = 5),
  status text NOT NULL DEFAULT 'waiting' CHECK (status IN ('waiting','playing','completed')),
  round_deadline_at timestamptz,
  winner_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_ready boolean NOT NULL DEFAULT false,
  partner_ready boolean NOT NULL DEFAULT false,
  created_score integer NOT NULL DEFAULT 0 CHECK (created_score >= 0),
  partner_score integer NOT NULL DEFAULT 0 CHECK (partner_score >= 0),
  last_round_results jsonb NOT NULL DEFAULT '[]'::jsonb,
  updated_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(created_by, partner_id, status)
);

ALTER TABLE IF EXISTS public.name_city_animal_games ADD COLUMN IF NOT EXISTS last_round_results jsonb NOT NULL DEFAULT '[]'::jsonb;

-- Idempotent upgrade from the original 3-category version.
ALTER TABLE IF EXISTS public.name_city_animal_dictionary
  DROP CONSTRAINT IF EXISTS name_city_animal_dictionary_category_check;
ALTER TABLE IF EXISTS public.name_city_animal_dictionary
  DROP CONSTRAINT IF EXISTS name_city_animal_dictionary_category_check1;
DO $$
BEGIN
  IF to_regclass('public.name_city_animal_dictionary') IS NOT NULL THEN
    IF NOT EXISTS (
      SELECT 1 FROM pg_constraint c
      WHERE c.conrelid='public.name_city_animal_dictionary'::regclass
        AND c.contype='c'
        AND pg_get_constraintdef(c.oid) LIKE '%plant%'
        AND pg_get_constraintdef(c.oid) LIKE '%country%'
    ) THEN
      ALTER TABLE public.name_city_animal_dictionary
        DROP CONSTRAINT IF EXISTS name_city_animal_dictionary_category_check;
      ALTER TABLE public.name_city_animal_dictionary
        ADD CONSTRAINT name_city_animal_dictionary_category_check
        CHECK (category IN ('name','city','animal','plant','thing','country'));
    END IF;
  END IF;
END $$;

ALTER TABLE IF EXISTS public.name_city_animal_answers
  ADD COLUMN IF NOT EXISTS plant text NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS thing text NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS country text NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS plant_normalized text NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS thing_normalized text NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS country_normalized text NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS plant_valid boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS thing_valid boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS country_valid boolean NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS public.name_city_animal_dictionary (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  language_code text NOT NULL CHECK (language_code IN ('tr','en','de','es','fr')),
  category text NOT NULL CHECK (category IN ('name','city','animal','plant','thing','country')),
  word text NOT NULL,
  normalized_word text NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  UNIQUE(language_code, category, normalized_word)
);

CREATE TABLE IF NOT EXISTS public.name_city_animal_answers (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  session_id uuid NOT NULL REFERENCES public.name_city_animal_games(session_id) ON DELETE CASCADE,
  round_number integer NOT NULL,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  name text NOT NULL DEFAULT '',
  city text NOT NULL DEFAULT '',
  animal text NOT NULL DEFAULT '',
  plant text NOT NULL DEFAULT '',
  thing text NOT NULL DEFAULT '',
  country text NOT NULL DEFAULT '',
  name_normalized text NOT NULL DEFAULT '',
  city_normalized text NOT NULL DEFAULT '',
  animal_normalized text NOT NULL DEFAULT '',
  plant_normalized text NOT NULL DEFAULT '',
  thing_normalized text NOT NULL DEFAULT '',
  country_normalized text NOT NULL DEFAULT '',
  name_valid boolean NOT NULL DEFAULT false,
  city_valid boolean NOT NULL DEFAULT false,
  animal_valid boolean NOT NULL DEFAULT false,
  plant_valid boolean NOT NULL DEFAULT false,
  thing_valid boolean NOT NULL DEFAULT false,
  country_valid boolean NOT NULL DEFAULT false,
  points integer NOT NULL DEFAULT 0,
  submitted_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(session_id, round_number, user_id)
);

CREATE INDEX IF NOT EXISTS nca_dictionary_lookup
  ON public.name_city_animal_dictionary(language_code, category, normalized_word);
CREATE INDEX IF NOT EXISTS nca_answers_session_round
  ON public.name_city_animal_answers(session_id, round_number);

ALTER TABLE public.name_city_animal_games ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.name_city_animal_answers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.name_city_animal_dictionary ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS nca_games_select ON public.name_city_animal_games;
CREATE POLICY nca_games_select ON public.name_city_animal_games
FOR SELECT TO authenticated
USING (auth.uid() = created_by OR auth.uid() = partner_id);

DROP POLICY IF EXISTS nca_answers_select ON public.name_city_animal_answers;
CREATE POLICY nca_answers_select ON public.name_city_animal_answers
FOR SELECT TO authenticated
USING (
  EXISTS (
    SELECT 1 FROM public.name_city_animal_games g
    WHERE g.session_id = name_city_animal_answers.session_id
      AND (g.created_by = auth.uid() OR g.partner_id = auth.uid())
  )
);

DROP POLICY IF EXISTS nca_dictionary_select ON public.name_city_animal_dictionary;
CREATE POLICY nca_dictionary_select ON public.name_city_animal_dictionary
FOR SELECT TO authenticated
USING (is_active = true);

CREATE OR REPLACE FUNCTION public.nca_normalize(p_value text)
RETURNS text
LANGUAGE sql IMMUTABLE
AS $$
  regexp_replace(
    replace(unaccent(lower(trim(coalesce(p_value,'')))), 'ı', 'i'),
    '[^a-z0-9]+',
    '',
    'g'
  )
$$;

CREATE OR REPLACE FUNCTION public.nca_pick_letter(p_language text)
RETURNS text
LANGUAGE plpgsql STABLE
AS $$
DECLARE
  v_letter text;
  v_letters text[];
BEGIN
  v_letters := CASE p_language
    WHEN 'tr' THEN ARRAY['A','B','C','Ç','D','E','F','G','H','İ','K','L','M','N','O','Ö','P','R','S','Ş','T','U','Ü','Y']
    WHEN 'de' THEN ARRAY['A','B','C','D','E','F','G','H','I','J','K','L','M','N','O','P','R','S','T','U','V','W','Z']
    WHEN 'es' THEN ARRAY['A','B','C','D','E','F','G','H','I','J','L','M','N','O','P','R','S','T','U','V','Y','Z']
    WHEN 'fr' THEN ARRAY['A','B','C','D','E','F','G','H','I','J','L','M','N','O','P','R','S','T','V','Y','Z']
    ELSE ARRAY['A','B','C','D','E','F','G','H','I','J','K','L','M','N','O','P','R','S','T','U','V','Y','Z']
  END;

  SELECT l
  INTO v_letter
  FROM unnest(v_letters) AS l
  WHERE EXISTS (
    SELECT 1 FROM public.name_city_animal_dictionary d
    WHERE d.language_code = p_language AND d.category = 'name'
      AND left(d.normalized_word, 1) = left(public.nca_normalize(l), 1)
      AND d.is_active
  )
  AND EXISTS (
    SELECT 1 FROM public.name_city_animal_dictionary d
    WHERE d.language_code = p_language AND d.category = 'city'
      AND left(d.normalized_word, 1) = left(public.nca_normalize(l), 1)
      AND d.is_active
  )
  AND EXISTS (
    SELECT 1 FROM public.name_city_animal_dictionary d
    WHERE d.language_code = p_language AND d.category = 'animal'
      AND left(d.normalized_word, 1) = left(public.nca_normalize(l), 1)
      AND d.is_active
  )
  AND EXISTS (SELECT 1 FROM public.name_city_animal_dictionary d WHERE d.language_code=p_language AND d.category='plant' AND left(d.normalized_word,1)=left(public.nca_normalize(l),1) AND d.is_active)
  AND EXISTS (SELECT 1 FROM public.name_city_animal_dictionary d WHERE d.language_code=p_language AND d.category='thing' AND left(d.normalized_word,1)=left(public.nca_normalize(l),1) AND d.is_active)
  AND EXISTS (SELECT 1 FROM public.name_city_animal_dictionary d WHERE d.language_code=p_language AND d.category='country' AND left(d.normalized_word,1)=left(public.nca_normalize(l),1) AND d.is_active)
  ORDER BY random()
  LIMIT 1;

  IF v_letter IS NULL THEN
    RAISE EXCEPTION 'NO_PLAYABLE_LETTER_FOR_LANGUAGE';
  END IF;
  RETURN v_letter;
END;
$$;

CREATE OR REPLACE FUNCTION public.nca_state(p_session_id uuid)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public, pg_temp
AS $$
DECLARE
  g public.name_city_animal_games;
  v_me uuid := auth.uid();
  v_created_submitted boolean;
  v_partner_submitted boolean;
  v_results jsonb;
BEGIN
  SELECT * INTO g
  FROM public.name_city_animal_games
  WHERE session_id = p_session_id
    AND (created_by = v_me OR partner_id = v_me);

  IF NOT FOUND THEN RAISE EXCEPTION 'NCA_SESSION_NOT_FOUND'; END IF;

  SELECT EXISTS (
    SELECT 1 FROM public.name_city_animal_answers a
    WHERE a.session_id = g.session_id AND a.round_number = g.round_number AND a.user_id = g.created_by
  ) INTO v_created_submitted;

  SELECT EXISTS (
    SELECT 1 FROM public.name_city_animal_answers a
    WHERE a.session_id = g.session_id AND a.round_number = g.round_number AND a.user_id = g.partner_id
  ) INTO v_partner_submitted;

  SELECT COALESCE(
    (
      SELECT jsonb_agg(
        jsonb_build_object(
          'user_id', a.user_id,
          'name', a.name,
          'city', a.city,
          'animal', a.animal,
          'plant', a.plant,
          'thing', a.thing,
          'country', a.country,
          'name_valid', a.name_valid,
          'city_valid', a.city_valid,
          'animal_valid', a.animal_valid,
          'plant_valid', a.plant_valid,
          'thing_valid', a.thing_valid,
          'country_valid', a.country_valid,
          'points', a.points
        ) ORDER BY a.submitted_at
      )
      FROM public.name_city_animal_answers a
      WHERE a.session_id = g.session_id AND a.round_number = g.round_number
    ),
    g.last_round_results,
    '[]'::jsonb
  ) INTO v_results;

  RETURN jsonb_build_object(
    'session_id', g.session_id,
    'created_by', g.created_by,
    'partner_id', g.partner_id,
    'language_code', g.language_code,
    'current_letter', g.current_letter,
    'round_number', g.round_number,
    'total_rounds', g.total_rounds,
    'status', g.status,
    'round_deadline_at', g.round_deadline_at,
    'winner_user_id', g.winner_user_id,
    'created_ready', g.created_ready,
    'partner_ready', g.partner_ready,
    'created_score', g.created_score,
    'partner_score', g.partner_score,
    'created_submitted', v_created_submitted,
    'partner_submitted', v_partner_submitted,
    'round_results', v_results
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.create_or_join_name_city_animal_session(
  p_partner_id uuid,
  p_language_code text
)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public, pg_temp
AS $$
DECLARE
  v_me uuid := auth.uid();
  v_game public.name_city_animal_games;
BEGIN
  IF v_me IS NULL THEN RAISE EXCEPTION 'AUTH_REQUIRED'; END IF;
  IF p_partner_id IS NULL OR p_partner_id = v_me THEN RAISE EXCEPTION 'INVALID_PARTNER'; END IF;
  IF p_language_code NOT IN ('tr','en','de','es','fr') THEN RAISE EXCEPTION 'UNSUPPORTED_LANGUAGE'; END IF;

  SELECT * INTO v_game
  FROM public.name_city_animal_games
  WHERE status IN ('waiting','playing')
    AND ((created_by=v_me AND partner_id=p_partner_id) OR (created_by=p_partner_id AND partner_id=v_me))
  ORDER BY created_at DESC LIMIT 1;

  IF FOUND THEN RETURN public.nca_state(v_game.session_id); END IF;

  INSERT INTO public.name_city_animal_games(created_by,partner_id,language_code,current_letter,round_number,total_rounds,status)
  VALUES(v_me,p_partner_id,p_language_code,'A',1,5,'waiting')
  RETURNING * INTO v_game;

  RETURN public.nca_state(v_game.session_id);
END;
$$;

CREATE OR REPLACE FUNCTION public.get_name_city_animal_state(p_session_id uuid)
RETURNS jsonb
LANGUAGE sql SECURITY DEFINER SET search_path=public, pg_temp
AS $$
  SELECT public.nca_state(p_session_id);
$$;

CREATE OR REPLACE FUNCTION public.set_name_city_animal_ready(
  p_session_id uuid,
  p_ready boolean
)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public, pg_temp
AS $$
DECLARE
  g public.name_city_animal_games;
  v_me uuid := auth.uid();
BEGIN
  SELECT * INTO g FROM public.name_city_animal_games
  WHERE session_id=p_session_id AND (created_by=v_me OR partner_id=v_me) FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'NCA_SESSION_NOT_FOUND'; END IF;
  IF g.status <> 'waiting' THEN RETURN public.nca_state(g.session_id); END IF;

  IF v_me=g.created_by THEN
    UPDATE public.name_city_animal_games SET created_ready=p_ready, updated_at=now() WHERE session_id=g.session_id;
  ELSE
    UPDATE public.name_city_animal_games SET partner_ready=p_ready, updated_at=now() WHERE session_id=g.session_id;
  END IF;

  RETURN public.nca_state(g.session_id);
END;
$$;

CREATE OR REPLACE FUNCTION public.start_name_city_animal(p_session_id uuid)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public, pg_temp
AS $$
DECLARE
  g public.name_city_animal_games;
  v_letter text;
BEGIN
  SELECT * INTO g FROM public.name_city_animal_games
  WHERE session_id=p_session_id
    AND (created_by=auth.uid() OR partner_id=auth.uid())
  FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'NCA_SESSION_NOT_FOUND'; END IF;
  IF NOT (g.created_ready AND g.partner_ready) THEN RETURN public.nca_state(g.session_id); END IF;
  IF g.status='completed' THEN RETURN public.nca_state(g.session_id); END IF;
  IF g.status='playing' THEN RETURN public.nca_state(g.session_id); END IF;

  v_letter := public.nca_pick_letter(g.language_code);
  UPDATE public.name_city_animal_games
  SET status='playing',
      current_letter=v_letter,
      round_number=1,
      round_deadline_at=now() + interval '45 seconds',
      updated_at=now()
  WHERE session_id=g.session_id;

  RETURN public.nca_state(g.session_id);
END;
$$;

CREATE OR REPLACE FUNCTION public.nca_validate(
  p_language text,
  p_category text,
  p_word text,
  p_letter text
)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public, pg_temp
AS $$
  SELECT
    public.nca_normalize(p_word) <> ''
    AND left(public.nca_normalize(p_word),1) = left(public.nca_normalize(p_letter),1)
    AND EXISTS (
      SELECT 1
      FROM public.name_city_animal_dictionary d
      WHERE d.language_code=p_language
        AND d.category=p_category
        AND d.normalized_word=public.nca_normalize(p_word)
        AND d.is_active
    );
$$;

CREATE OR REPLACE FUNCTION public.nca_resolve_round(p_session_id uuid)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public, pg_temp
AS $$
DECLARE
  g public.name_city_animal_games;
  a record;
  v_next_letter text;
  v_created_round_points integer := 0;
  v_partner_round_points integer := 0;
  v_new_created_score integer := 0;
  v_new_partner_score integer := 0;
  v_results jsonb := '[]'::jsonb;
BEGIN
  SELECT * INTO g FROM public.name_city_animal_games
  WHERE session_id=p_session_id
    AND (created_by=auth.uid() OR partner_id=auth.uid())
  FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'NCA_SESSION_NOT_FOUND'; END IF;
  IF g.status <> 'playing' THEN RETURN public.nca_state(g.session_id); END IF;

  FOR a IN
    SELECT * FROM public.name_city_animal_answers
    WHERE session_id=g.session_id AND round_number=g.round_number
    FOR UPDATE
  LOOP
    UPDATE public.name_city_animal_answers
    SET
      name_valid = public.nca_validate(g.language_code,'name',a.name,g.current_letter),
      city_valid = public.nca_validate(g.language_code,'city',a.city,g.current_letter),
      animal_valid = public.nca_validate(g.language_code,'animal',a.animal,g.current_letter),
      plant_valid = public.nca_validate(g.language_code,'plant',a.plant,g.current_letter),
      thing_valid = public.nca_validate(g.language_code,'thing',a.thing,g.current_letter),
      country_valid = public.nca_validate(g.language_code,'country',a.country,g.current_letter)
    WHERE id=a.id;
  END LOOP;

  -- Unique valid answer = 2 points. Same valid answer = 1 point each.
  UPDATE public.name_city_animal_answers a
  SET points =
    (CASE WHEN a.name_valid THEN
      CASE WHEN (
        SELECT count(*) FROM public.name_city_animal_answers b
        WHERE b.session_id=a.session_id AND b.round_number=a.round_number
          AND b.name_valid AND b.name_normalized=a.name_normalized
      ) > 1 THEN 1 ELSE 2 END ELSE 0 END)
    +
    (CASE WHEN a.city_valid THEN
      CASE WHEN (
        SELECT count(*) FROM public.name_city_animal_answers b
        WHERE b.session_id=a.session_id AND b.round_number=a.round_number
          AND b.city_valid AND b.city_normalized=a.city_normalized
      ) > 1 THEN 1 ELSE 2 END ELSE 0 END)
    +
    (CASE WHEN a.animal_valid THEN
      CASE WHEN (SELECT count(*) FROM public.name_city_animal_answers b WHERE b.session_id=a.session_id AND b.round_number=a.round_number AND b.animal_valid AND b.animal_normalized=a.animal_normalized) > 1 THEN 1 ELSE 2 END ELSE 0 END)
    +
    (CASE WHEN a.plant_valid THEN
      CASE WHEN (SELECT count(*) FROM public.name_city_animal_answers b WHERE b.session_id=a.session_id AND b.round_number=a.round_number AND b.plant_valid AND b.plant_normalized=a.plant_normalized) > 1 THEN 1 ELSE 2 END ELSE 0 END)
    +
    (CASE WHEN a.thing_valid THEN
      CASE WHEN (SELECT count(*) FROM public.name_city_animal_answers b WHERE b.session_id=a.session_id AND b.round_number=a.round_number AND b.thing_valid AND b.thing_normalized=a.thing_normalized) > 1 THEN 1 ELSE 2 END ELSE 0 END)
    +
    (CASE WHEN a.country_valid THEN
      CASE WHEN (SELECT count(*) FROM public.name_city_animal_answers b WHERE b.session_id=a.session_id AND b.round_number=a.round_number AND b.country_valid AND b.country_normalized=a.country_normalized) > 1 THEN 1 ELSE 2 END ELSE 0 END)
  WHERE a.session_id=g.session_id AND a.round_number=g.round_number;

  SELECT
    COALESCE((SELECT points FROM public.name_city_animal_answers WHERE session_id=g.session_id AND round_number=g.round_number AND user_id=g.created_by),0),
    COALESCE((SELECT points FROM public.name_city_animal_answers WHERE session_id=g.session_id AND round_number=g.round_number AND user_id=g.partner_id),0)
  INTO v_created_round_points, v_partner_round_points;

  v_new_created_score := g.created_score + v_created_round_points;
  v_new_partner_score := g.partner_score + v_partner_round_points;

  SELECT COALESCE(jsonb_agg(
    jsonb_build_object(
      'user_id', a.user_id,
      'name', a.name,
      'city', a.city,
      'animal', a.animal,
      'name_valid', a.name_valid,
      'city_valid', a.city_valid,
      'animal_valid', a.animal_valid,
      'points', a.points
    ) ORDER BY a.submitted_at
  ), '[]'::jsonb)
  INTO v_results
  FROM public.name_city_animal_answers a
  WHERE a.session_id=g.session_id AND a.round_number=g.round_number;

  UPDATE public.name_city_animal_games
  SET
    created_score = v_new_created_score,
    partner_score = v_new_partner_score,
    updated_at=now()
  WHERE session_id=g.session_id;

  IF g.round_number >= g.total_rounds THEN
    UPDATE public.name_city_animal_games
    SET status='completed',
        round_deadline_at=NULL,
        last_round_results=v_results,
        winner_user_id=CASE
          WHEN v_new_created_score > v_new_partner_score THEN created_by
          WHEN v_new_created_score < v_new_partner_score THEN partner_id
          ELSE NULL
        END,
        updated_at=now()
    WHERE session_id=g.session_id;
  ELSE
    v_next_letter := public.nca_pick_letter(g.language_code);
    UPDATE public.name_city_animal_games
    SET round_number=g.round_number+1,
        current_letter=v_next_letter,
        last_round_results=v_results,
        round_deadline_at=now()+interval '45 seconds',
        updated_at=now()
    WHERE session_id=g.session_id;
  END IF;

  RETURN public.nca_state(g.session_id);
END;
$$;

CREATE OR REPLACE FUNCTION public.submit_name_city_animal_answers(
  p_session_id uuid,
  p_name text,
  p_city text,
  p_animal text,
  p_plant text,
  p_thing text,
  p_country text
)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public, pg_temp
AS $$
DECLARE
  g public.name_city_animal_games;
  v_me uuid := auth.uid();
  v_name text := trim(coalesce(p_name,''));
  v_city text := trim(coalesce(p_city,''));
  v_animal text := trim(coalesce(p_animal,''));
  v_plant text := trim(coalesce(p_plant,''));
  v_thing text := trim(coalesce(p_thing,''));
  v_country text := trim(coalesce(p_country,''));
  v_deadline boolean;
  v_count integer;
BEGIN
  SELECT * INTO g FROM public.name_city_animal_games
  WHERE session_id=p_session_id AND (created_by=v_me OR partner_id=v_me) FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'NCA_SESSION_NOT_FOUND'; END IF;
  IF g.status <> 'playing' THEN RETURN public.nca_state(g.session_id); END IF;

  IF now() > coalesce(g.round_deadline_at, now()) THEN
    RETURN public.expire_name_city_animal_round(g.session_id);
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.name_city_animal_answers
    WHERE session_id=g.session_id AND round_number=g.round_number AND user_id=v_me
  ) THEN
    RETURN public.nca_state(g.session_id);
  END IF;

  INSERT INTO public.name_city_animal_answers(
    session_id,round_number,user_id,name,city,animal,plant,thing,country,
    name_normalized,city_normalized,animal_normalized,plant_normalized,thing_normalized,country_normalized
  ) VALUES(
    g.session_id,g.round_number,v_me,v_name,v_city,v_animal,v_plant,v_thing,v_country,
    public.nca_normalize(v_name),public.nca_normalize(v_city),public.nca_normalize(v_animal),public.nca_normalize(v_plant),public.nca_normalize(v_thing),public.nca_normalize(v_country)
  );

  SELECT count(*) INTO v_count
  FROM public.name_city_animal_answers
  WHERE session_id=g.session_id AND round_number=g.round_number;

  UPDATE public.name_city_animal_games SET updated_at=now() WHERE session_id=g.session_id;

  IF v_count >= 2 THEN
    RETURN public.nca_resolve_round(g.session_id);
  END IF;

  RETURN public.nca_state(g.session_id);
END;
$$;

CREATE OR REPLACE FUNCTION public.expire_name_city_animal_round(p_session_id uuid)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public, pg_temp
AS $$
DECLARE
  g public.name_city_animal_games;
  v_count integer;
BEGIN
  SELECT * INTO g FROM public.name_city_animal_games
  WHERE session_id=p_session_id AND (created_by=auth.uid() OR partner_id=auth.uid()) FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'NCA_SESSION_NOT_FOUND'; END IF;
  IF g.status <> 'playing' THEN RETURN public.nca_state(g.session_id); END IF;
  IF now() < coalesce(g.round_deadline_at, now()) THEN RETURN public.nca_state(g.session_id); END IF;

  SELECT count(*) INTO v_count
  FROM public.name_city_animal_answers
  WHERE session_id=g.session_id AND round_number=g.round_number;

  IF v_count < 2 THEN
    INSERT INTO public.name_city_animal_answers(session_id,round_number,user_id)
    SELECT g.session_id,g.round_number,p.id
    FROM (VALUES (g.created_by),(g.partner_id)) p(id)
    WHERE NOT EXISTS (
      SELECT 1 FROM public.name_city_animal_answers a
      WHERE a.session_id=g.session_id AND a.round_number=g.round_number AND a.user_id=p.id
    );
  END IF;

  RETURN public.nca_resolve_round(g.session_id);
END;
$$;

CREATE OR REPLACE FUNCTION public.surrender_name_city_animal(p_session_id uuid)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public, pg_temp
AS $$
DECLARE
  g public.name_city_animal_games;
  v_me uuid := auth.uid();
BEGIN
  SELECT * INTO g FROM public.name_city_animal_games
  WHERE session_id=p_session_id AND (created_by=v_me OR partner_id=v_me) FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'NCA_SESSION_NOT_FOUND'; END IF;
  UPDATE public.name_city_animal_games
  SET status='completed',
      winner_user_id=CASE WHEN v_me=created_by THEN partner_id ELSE created_by END,
      round_deadline_at=NULL,
      updated_at=now()
  WHERE session_id=g.session_id;
  RETURN public.nca_state(g.session_id);
END;
$$;


